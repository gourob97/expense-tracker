// Builds the app's icon files from the lucide-static npm package (https://lucide.dev, ISC licence).
//   npm pack lucide-static && tar xzf lucide-static-*.tgz
//   node scripts/build-lucide-icons.mjs ./package
// Writes:
//   lucide-icons.js  every icon and its search words; loaded only when someone searches in the category editor
//   icons-builtin.js the built-in category icons and the suggested ones, small enough to load with the app
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkg = process.argv[2];
if (!pkg) { console.error("usage: node scripts/build-lucide-icons.mjs <path to extracted lucide-static package>"); process.exit(1); }
const read = f => JSON.parse(readFileSync(join(pkg, f), "utf8"));
const { version } = read("package.json");
const nodes = read("icon-nodes.json"), tags = read("tags.json");
const license = readFileSync(join(pkg, "LICENSE"), "utf8").trim();

const esc = v => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const markup = name => nodes[name].map(([tag, attrs]) =>
  `<${tag}${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => ` ${k}="${esc(v)}"`).join("")}/>`).join("");

// The app's own names for the built-in category icons (stored on existing categories) and the Lucide icon each one shows
const BUILTIN = {
  food: "utensils", transport: "bus", bills: "zap", rent: "house", shopping: "shopping-bag", health: "heart-pulse",
  fun: "tv-minimal-play", gift: "gift", book: "book", phone: "smartphone", plane: "plane", coffee: "coffee",
  paw: "paw-print", dumbbell: "dumbbell", tag: "tag", other: "ellipsis"
};
// Shown after the built-ins before anything is typed: everyday spending
const SUGGESTED = [
  "shopping-cart", "car", "motorbike", "bike", "car-taxi-front", "train-front", "fuel", "baby",
  "graduation-cap", "pill", "stethoscope", "wifi", "smartphone-charging", "lightbulb", "droplet", "flame",
  "wrench", "shirt", "scissors", "piggy-bank", "credit-card", "wallet", "banknote", "receipt",
  "briefcase", "landmark", "hand-heart", "sofa", "gamepad-2", "ticket", "cake", "hotel"
];
for (const n of [...Object.values(BUILTIN), ...SUGGESTED]) if (!nodes[n]) throw new Error(`lucide-static ${version} has no icon "${n}"`);

const header = `// Generated by scripts/build-lucide-icons.mjs from lucide-static ${version}. Do not edit by hand.\n/*\n${license}\n*/\n`;
const obj = entries => "{\n" + entries.map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`).join(",\n") + "\n}";

const names = Object.keys(nodes).sort();
writeFileSync("lucide-icons.js", header +
  `export const LUCIDE_VERSION = ${JSON.stringify(version)};\n` +
  `export const ICONS = ${obj(names.map(n => [n, markup(n)]))};\n` +
  `export const TAGS = ${obj(names.map(n => [n, (tags[n] || []).join(" ")]))};\n`);
writeFileSync("icons-builtin.js", header +
  `export const BUILTIN = ${obj(Object.entries(BUILTIN).map(([k, n]) => [k, { lucide: n, svg: markup(n) }]))};\n` +
  `export const SUGGESTED = ${obj(SUGGESTED.map(n => [n, markup(n)]))};\n`);
console.log(`lucide-static ${version}: ${names.length} icons`);
